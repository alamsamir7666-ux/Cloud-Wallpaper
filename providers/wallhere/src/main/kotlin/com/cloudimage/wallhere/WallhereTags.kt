package com.cloudimage.wallhere

/**
 * The site's tag catalogue, baked — the precision surface this provider
 * rides for search.
 *
 * WallHere's plain search (`/en/wallpapers?q=`) answers every query, but
 * fuzzily; the site's REAL precision surface is its tag pages —
 * `/en/tag/{id}` — one strictly-tagged grid each, twenty-four items per
 * page, paginating thousands of pages deep (Nature: 6,250; Anime: 6,645).
 * The catalogue below is site-attested twice over: the seeds are the
 * `/en/tags` index's own first page (the most-used tags on the site), and
 * the expansion walked each tag page's own "Similar Tags" cloud, with
 * every name taken from the tag page's `<title>` — the site's canonical
 * spelling (October 2026). Junk families the index mixes in (years,
 * EXIF/camera/geodata tags, uploader-spam batches) are filtered out.
 *
 * Baking the catalogue buys three things: [suggestTags] answers the
 * search bar offline from a FRESH instance (v1.0.0 could only suggest
 * tags it had already seen in fetched grids), [search] walks the exact
 * tag's own grid when the query names one (precise results, deep
 * pagination, honest purity), and the category lanes address real tag
 * pages instead of fuzzy searches.
 *
 * Matching is deliberately simple and total: normalize the query
 * (lowercase, whitespace collapsed), then match names exactly. No exact
 * match is an honest miss: the caller falls back to the site's own
 * `q=` search, which serves every other query.

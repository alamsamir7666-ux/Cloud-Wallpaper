    /** The query's normalized form: lowercase, whitespace collapsed. */
    private fun normalize(query: String): String = query.trim().lowercase().replace(Regex("\\s+"), " ")

    /**
     * The tag the query NAMES, when it names one — exact
     * (case-insensitive, whitespace-tolerant) match against the
     * catalogue. Null is an honest miss, never an error.
     */
    fun exactTag(query: String): TagEntry? {
        val q = normalize(query)
        if (q.isEmpty()) return null
        return entries.firstOrNull { it.name.lowercase() == q }
    }

    /**
     * Offline search-bar suggestions: exact matches first, then
     * prefixes, then contains, each group in catalogue (popularity)
     * order. Adult-vocabulary tags are withheld from SUGGESTIONS — the
     * check is per WORD of the name ("panties down" is as withheld as
     * "panties") — while the tag itself still resolves when typed in
     * full.
     */
    fun suggestions(
        query: String,
        limit: Int,
        isAdultWord: (String) -> Boolean,
    ): List<String> {
        val q = normalize(query)
        if (q.isEmpty() || q.length < 2) return emptyList()
        val exact = mutableListOf<String>()
        val prefix = mutableListOf<String>()
        val contains = mutableListOf<String>()
        for (entry in entries) {
            val name = entry.name
            val lower = name.lowercase()
            val words = lower.split(' ', '-', '_')
            if (words.any { isAdultWord(it) }) continue
            when {
                lower == q -> exact.add(name)
                lower.startsWith(q) -> prefix.add(name)
                lower.contains(q) -> contains.add(name)
            }
        }
        return (exact + prefix + contains)
            .distinct()
            .take(limit)
    }
